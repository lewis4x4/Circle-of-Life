pol = q("""select schemaname, tablename, policyname, coalesce(qual,''), coalesce(with_check,'')
 from pg_policies where (coalesce(qual,'')||coalesce(with_check,'')) ~ '''(nurse|dietary)''' order by 1,2,3""")
print(f"-- {len(pol)} policies")
for s, t, p, qual, chk in pol:
    parts = []
    qual, chk = qual.strip(), chk.strip()
    if qual: parts.append(f"USING ({swap(qual, p)})")
    if chk: parts.append(f"WITH CHECK ({swap(chk, p)})")
    print(f"ALTER POLICY {ident(p)} ON {ident(s)}.{ident(t)}\n  " + "\n  ".join(parts) + ";")

