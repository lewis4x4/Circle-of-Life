import re, subprocess, sys
PSQL = ["/tmp/loc-psql.sh", "-d", "haven"]
def q(sql):
    out = subprocess.run(PSQL + ["-F", "\x1f", "-R", "\x1e", "-c", sql], capture_output=True, text=True, check=True).stdout
    return [[f.strip("\n") for f in r.split("\x1f")] for r in out.split("\x1e") if r.strip()]

LIST_BEFORE = re.compile(r"[\[(,]\s*$")
LIST_AFTER = re.compile(r"^\s*[,\])]")

def swap(text, where):
    # nurse -> med_tech: every role literal.
    text = re.sub(r"'nurse'", "'med_tech'", text)
    # cook joins dietary wherever dietary is listed.
    out, i = [], 0
    for m in re.finditer(r"'dietary'((?:::[a-z_]+)?)", text):
        before, after = text[:m.start()], text[m.end():]
        if not LIST_BEFORE.search(before) or not LIST_AFTER.match(after):
            sys.exit(f"dietary outside a list in {where}: ...{before[-60:]}|{m.group(0)}|{after[:40]}...")
        out.append(text[i:m.end()]); out.append(f", 'cook'{m.group(1)}"); i = m.end()
    out.append(text[i:])
    return "".join(out)

def ident(s): return '"' + s.replace('"', '""') + '"'

