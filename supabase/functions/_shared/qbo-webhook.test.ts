  body.fill(0);
  const result = success(await promise);
  equal(
    Array.from(result.evidence.copyAuthenticatedBody()),
    Array.from(original),
    "Input bytes must be privately owned before async work",
  );
  const first = result.evidence.copyAuthenticatedBody();
