import { createHash, createHmac } from "node:crypto";
import {
  QBO_WEBHOOK_LIMITS,
  type QboWebhookError,
  type QboWebhookResult,
  validateQboWebhook,
} from "./qbo-webhook.ts";
const key = "synthetic-verifier-canary-DO-NOT-LOG";
const encoder = new TextEncoder();
const event = (change: Record<string, unknown> = {}) => ({
  specversion: "1.0",
  id: "provider-event-1",
  source: "intuit.opaque/source=",
  type: "qbo.invoice.updated.v1",
  intuitaccountid: "9341455327810551",
  intuitentityid: "123",
  time: "2026-09-09T04:12:31.179851517Z",
  datacontenttype: "application/json",
  data: {},
  ...change,
});
function assert(value: unknown, message: string): asserts value {
  if (!value) throw new Error(message);
}
function equal(actual: unknown, expected: unknown, message: string) {
  assert(JSON.stringify(actual) === JSON.stringify(expected), message);
}
function signature(body: Uint8Array, secret = key) {
  return createHmac("sha256", secret).update(body).digest("base64");
}
function digest(body: Uint8Array) {
  return createHash("sha256").update(body).digest("hex");
}
function input(
  body: Uint8Array,
  secret = key,
  contentType = "application/json",
) {
  return {
    body,
    verifierToken: secret,
    headers: [["Content-Type", contentType], [
      "intuit-signature",
      signature(body, secret),
    ]] as [string, string][],
  };
}
function json(value: unknown) {
  return encoder.encode(JSON.stringify(value));
}
async function validate(value: unknown) {
  return await validateQboWebhook(input(json(value)));
}
function success(result: QboWebhookResult) {
  assert(result.ok, "Expected valid signature and schema");
  return result;
}
function rejected(
  result: QboWebhookResult,
  code: QboWebhookError,
  authenticated: boolean,
) {
  assert(
    !result.ok && result.code === code &&
      result.authenticated === authenticated,
    `Expected fixed rejection ${code}/${authenticated}`,
  );
  return result;
}

Deno.test("HFA-024: RFC4231 known HMAC vector authenticates before JSON rejection", async () => {
  // RFC4231 §4.3 independently published test case2, not generated by the validator.
  const body = encoder.encode("what do ya want for nothing?");
  const expectedHex =
    "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843";
  const expected = btoa(
    String.fromCharCode(
      ...expectedHex.match(/../g)!.map((value) => parseInt(value, 16)),
    ),
  );
  assert(
    signature(body, "Jefe") === expected,
    "Independent Node oracle must match published vector",
  );
  const result = await validateQboWebhook({
    body,
    verifierToken: "Jefe",
    headers: [["content-type", "application/json"], [
      "intuit-signature",
      expected,
    ]],
  });
  const failure = rejected(result, "invalid_json", true);
  assert(
    failure.authenticated && failure.evidence.body_sha256 === digest(body),
    "Authenticated malformed content must retain exact evidence",
  );
});
Deno.test("HFA-024: exact whitespace and nonASCII bytes use independent HMAC and digest oracles", async () => {
  const raw = ` \n[\n ${
    JSON.stringify(event({ data: { name: "患者 café 🧾", amount: 17 } }))
  }\n]\r\n`;
  const body = encoder.encode(raw);
  const result = success(await validateQboWebhook(input(body)));
  assert(
    result.evidence.body_sha256 === digest(body),
    "Whole-body bytes must match independent digest",
  );
  const range = result.privateMetadata.eventByteRanges[0];
  assert(
    result.privateMetadata.events[0].event_bytes_sha256 ===
      digest(body.slice(range.start, range.end)),
    "Event exact-byte hash must match independent digest",
  );
  equal(
    Array.from(result.evidence.copyAuthenticatedBody()),
    Array.from(body),
    "Original authenticated bytes retained",
  );
  const altered = encoder.encode(raw.replace("café", "cafe"));
  rejected(
    await validateQboWebhook({ ...input(body), body: altered }),
    "signature_invalid",
    false,
  );
});
